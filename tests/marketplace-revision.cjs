/* Browser regressions for the simplified marketplace. No live model requests. */
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const base = process.env.BASE_URL || 'http://127.0.0.1:4186';
let checks = 0;
const check = (condition, label) => { assert.ok(condition, label); checks++; };
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || '/snap/bin/chromium', args: ['--no-sandbox'] });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage(), errors = [], unexpectedModelRequests = [];
    page.on('pageerror', error => errors.push(error.message));
    await context.route('**/*', async route => {
      const request = route.request(), url = new URL(request.url());
      if (url.pathname.endsWith('/config.json')) return route.fulfill({ json: { api_configs: { gpt: { api_key: '', base_url: '', model: ['local'] } } } });
      if (request.method() === 'POST') { unexpectedModelRequests.push(url.origin + url.pathname); return route.abort(); }
      if (url.origin !== new URL(base).origin) return route.abort();
      return route.continue();
    });
    await page.goto(base);
    check(!(await page.locator('.auth-card').innerText()).includes('Seed accounts'), 'Login hides seed-account instructions');
    check(!(await page.locator('.auth-card').innerText()).includes('buyer@almanar.sa'), 'Login hides sample credentials');
    check(await page.getAttribute('.brand-logo', 'src') === 'logo.png', 'Top bar uses the full logo asset');
    check(await page.getByRole('button', { name: /Notifications/i }).count() === 0, 'Top bar has no notifications button');
    await page.fill('#authEmail', 'buyer@almanar.sa');
    await page.fill('#authPassword', '111111');
    await page.click('#authForm button[type="submit"]');
    await page.waitForSelector('.home-guide');
    const go = route => page.evaluate(route => navigate(route), route);
    const language = code => page.click(`[data-lang="${code}"]`);
    const bubble = id => page.locator(`.chat-message[data-message-id="${id}"] .chat-bubble`);
    for (const code of ['EN', 'ZH', 'SA']) {
      await language(code);
      await go('overview');
      check(await page.locator('.showcase-provider').count() === 0, code + ' home removes the provider showcase');
      const assistantNames = { EN: ['Buyer Assistant', 'Seller Assistant'], ZH: ['买方助手', '卖方助手'], SA: ['مساعد المشتري', 'مساعد البائع'] }[code];
      check(await page.locator('.nav-item[data-screen="buyer-agent"] [data-i18n]').innerText() === assistantNames[0], code + ' buyer navigation uses a complete localized name');
      check(await page.locator('.nav-item[data-screen="seller-agent"] [data-i18n]').innerText() === assistantNames[1], code + ' seller navigation uses a complete localized name');
      check(await page.locator('.home-guide input, .home-guide textarea, .home-guide form').count() === 0, code + ' home guide has no chat input');
      check(await page.locator('.home-guide-bubble [data-no-translate]').count() === 1, code + ' home guide has one welcome message');
      check(await page.locator('#assistantForm, #assistantMessages').count() === 0, code + ' home omits the old embedded chat');
      await go('catalog');
      const allProducts = await page.locator('.product-card').count();
      const category = name => page.locator(`.marketplace-categories [data-category="${name}"]`);
      const matchesCategory = name => page.evaluate(name => { const buttons = [...document.querySelectorAll('.product-card [data-product]')]; return buttons.length === db.products.filter(product => product.category === name).length && buttons.every(button => SaqrDB.product(button.dataset.product, db)?.category === name); }, name);
      await category('AI Agents').click();
      check(await page.evaluate(() => state.catalogCategory) === 'AI Agents' && await matchesCategory('AI Agents'), code + ' first category click filters matching products');
      await go('overview');
      check(await page.locator('.category-section [data-category="AI Agents"].selected').count() === 1, code + ' home reflects the selected catalog category');
      await go('catalog');
      await category('AI Agents').click();
      check(await page.evaluate(() => state.catalogCategory) === 'All categories' && await page.locator('.product-card').count() === allProducts, code + ' clicking the active category restores every product');
      check(await page.locator('.marketplace-categories .category-tile.selected').count() === 0, code + ' category cancellation clears the selected tile');
      await category('AI Agents').click();
      await category('Automation').click();
      check(await page.evaluate(() => state.catalogCategory) === 'Automation' && await matchesCategory('Automation'), code + ' clicking another category changes the filter');
      await category('Automation').click();
      check(await page.evaluate(() => state.catalogCategory) === 'All categories' && await page.locator('.product-card').count() === allProducts, code + ' cancelling the replacement category restores every product');
      await go('overview');
      check(await page.locator('.category-section .category-tile.selected').count() === 0, code + ' home reflects the cancelled category');
      await page.click('.home-guide-avatar');
      check(await page.evaluate(() => state.screen) === 'guide-agent', code + ' bird opens the dedicated guide');
      check(await page.locator('.agent-workspace[data-agent-role="guide"]').count() === 1, code + ' guide has a conversation workspace');
    }
    for (const route of ['catalog', 'sourcing']) {
      await page.locator(`.nav-item[data-screen="${route}"]`).click();
      check(await page.locator('.nav-item.active').count() === 1, route + ' has exactly one active navigation item');
      check(await page.getAttribute('.nav-item.active', 'data-screen') === route, route + ' highlights its own navigation item');
      check(await page.locator(`.nav-item[data-screen="${route}"] .nav-count`).count() === 0, route + ' has no count badge');
    }
    const badgeStyles = await page.locator('.nav-count').evaluateAll(nodes => nodes.map(node => ({ color: getComputedStyle(node).color, background: getComputedStyle(node).backgroundColor, accent: node.classList.contains('accent') })));
    check(badgeStyles.length > 0 && badgeStyles.every(item => !item.accent), 'Remaining count badges have no accent class');
    check(new Set(badgeStyles.map(item => item.color + '/' + item.background)).size === 1, 'Remaining count badges share a neutral appearance');
    check(badgeStyles.every(item => { const channels = item.background.match(/[\d.]+/g).slice(0, 3).map(Number); return Math.max(...channels) - Math.min(...channels) < 10; }), 'Count badge backgrounds are gray');
    await go('procurement');
    check(await page.locator('#pageWrap form, #pageWrap textarea, #pageWrap input').count() === 0, 'Procurement overview has no requirement form');
    check(await page.locator('#pageWrap [data-screen="compare"], #pageWrap [data-screen="evaluations"], #pageWrap [data-action="run-evaluation"]').count() === 0, 'Procurement overview has no comparison or evaluation entry');
    check(await page.locator('.procurement-step').count() >= 5, 'Procurement overview explains the process');
    for (const oldRoute of ['requests', 'compare', 'evaluations']) {
      await go(oldRoute);
      check(await page.evaluate(() => state.screen) === 'buyer-agent', oldRoute + ' navigation redirects to the buyer conversation');
      check(await page.locator('.agent-workspace[data-agent-role="buyer"]').count() === 1, oldRoute + ' renders a conversation');
    }
    await language('EN');
    await go('catalog');
    const original = await page.evaluate(() => { const p = SaqrDB.product('prd-nura-knowledge', db); return { name: p.name, description: p.description, summary: p.summary, support: p.support }; });
    for (const code of ['ZH', 'SA', 'EN']) {
      await language(code);
      const card = page.locator('.product-card').filter({ has: page.locator('[data-product="prd-nura-knowledge"]') });
      check(await card.locator('.product-card-body > p').innerText() === original.summary, code + ' card keeps the provider summary in its original language');
      await card.locator('[data-product="prd-nura-knowledge"]').click();
      check(await page.locator('#productTitle').innerText() === original.name, code + ' product name remains original');
      check(await page.locator('.product-introduction > p').innerText() === original.summary, code + ' modal shows the provider summary first');
      await page.locator('.product-full-introduction > summary').click();
      check(await page.locator('.product-introduction .markdown-body').innerText() === original.description, code + ' detailed introduction remains original');
      check((await page.locator('#productModal').innerText()).includes(original.support), code + ' provider support text remains original');
      check(await page.locator('#productModal [data-screen="compare"]').count() === 0, code + ' product modal has no comparison button');
      check(await page.locator('#productModal [data-action="place-order"]').count() === 1, code + ' product modal has an explicit purchase action');
      await page.click('[data-action="close-product"]');
    }
    await page.locator('[data-product="prd-nura-knowledge"]').first().click();
    const orderCount = await page.evaluate(() => db.orders.filter(order => order.buyerUserId === state.user.id).length);
    await page.click('#productModal [data-action="place-order"]');
    await page.waitForSelector('#checkoutForm');
    check(await page.evaluate(() => state.screen) === 'checkout', 'Purchase action opens checkout');
    check(await page.evaluate(() => db.orders.filter(order => order.buyerUserId === state.user.id).length) === orderCount, 'Checkout does not create an unpaid order');
    await page.locator('#checkoutForm').evaluate(form => form.requestSubmit());
    await page.waitForSelector('#paymentForm');
    await page.check('input[name="paymentMethod"][value="alipay"]');
    await page.locator('#paymentForm').evaluate(form => form.requestSubmit());
    await page.waitForSelector('[data-payment-state="processing"]');
    await page.waitForSelector('[data-payment-state="success"]');
    await page.click('[data-action="view-paid-order"]');
    await page.waitForSelector('.order-table');
    check(await page.evaluate(() => state.screen) === 'orders', 'Paid-order action opens purchase orders');
    check(await page.locator('[data-order-id]').count() === orderCount + 1, 'Successful demonstration payment creates an owned purchase order');
    await page.evaluate(() => {
      window.__translationCalls = [];
      window.__translationJobs = [];
      SaqrAgents.translateMessage = args => new Promise(resolve => { window.__translationCalls.push(args); window.__translationJobs.push({ args, resolve, done: false }); });
      state.selectedConversation = 'CONV-001';
    });
    await language('ZH');
    await go('messages');
    check(await bubble('MSG-002').innerText() === '可以。我们可以先手动上传文档，实施费 800 USD，月费 1,200 USD。', 'Received seed translation appears immediately in the current language');
    check(await page.locator('.chat-message.mine .chat-original, .chat-message.mine [data-translate-message]').count() === 0, 'Own messages have no translation option');
    check(await page.evaluate(() => window.__translationCalls.length) === 0, 'Saved seed translations need no model call');
    const addMessage = (id, text, sourceLanguage = 'English', mine = false) => page.evaluate(({ id, text, sourceLanguage, mine }) => {
      const conversation = db.conversations.find(item => item.id === 'CONV-001');
      conversation.messages.push({ id, senderId: mine ? state.user.id : 'USR-SELL-001', language: sourceLanguage, original: text, createdAt: new Date().toISOString() });
      SaqrDB.save(db);
      render();
    }, { id, text, sourceLanguage, mine });
    const calls = () => page.evaluate(() => window.__translationCalls.length);
    const resolve = (text, targetLanguage, translation) => page.evaluate(({ text, targetLanguage, translation }) => {
      const job = window.__translationJobs.find(item => !item.done && item.args.message === text && item.args.targetLanguage === targetLanguage);
      if (!job) throw new Error('Expected translation job was not queued');
      job.done = true;
      job.resolve({ translation, provider: 'live' });
    }, { text, targetLanguage, translation });
    await addMessage('REV-OWN', '我自己发送的中文不应被翻译。', 'Chinese', true);
    check(await calls() === 0, 'Own newly sent messages never trigger translation');
    const firstText = 'Please confirm the revised delivery scope.';
    await addMessage('REV-FIRST', firstText);
    await page.waitForFunction(() => window.__translationCalls.length === 1);
    check(await bubble('REV-FIRST').getAttribute('aria-busy') === 'true', 'New incoming message automatically enters translation');
    await page.fill('#conversationText', 'Draft remains while the translation resolves');
    await resolve(firstText, 'ZH', '请确认调整后的交付范围。');
    await page.waitForFunction(() => document.querySelector('[data-message-id="REV-FIRST"] .chat-bubble')?.textContent === '请确认调整后的交付范围。');
    check(await page.inputValue('#conversationText') === 'Draft remains while the translation resolves', 'Translation completion preserves the unsent composer draft');
    await go('overview'); await go('messages');
    check(await calls() === 1, 'Returning to a conversation reuses the translation cache');
    await language('SA');
    await page.waitForFunction(() => window.__translationCalls.length === 2);
    await resolve(firstText, 'SA', 'يرجى تأكيد نطاق التسليم المعدل.');
    await page.waitForFunction(() => document.querySelector('[data-message-id="REV-FIRST"] .chat-bubble')?.textContent === 'يرجى تأكيد نطاق التسليم المعدل.');
    check(await page.locator('.chat-message.mine .chat-original').count() === 0, 'Own original-language messages remain untranslatable after language changes');
    await language('ZH');
    const slowText = 'The connector review needs one more document.';
    await addMessage('REV-SLOW', slowText);
    await page.waitForFunction(() => window.__translationCalls.length === 3);
    await language('SA');
    await page.waitForFunction(() => window.__translationCalls.length === 4);
    await page.fill('#conversationText', 'Arabic view draft must survive stale and current translations');
    await resolve(slowText, 'ZH', '连接器评审还需要一份文档。');
    check(!(await bubble('REV-SLOW').innerText()).includes('连接器评审'), 'An inflight response for the previous language does not replace the active message');
    check(await page.inputValue('#conversationText') === 'Arabic view draft must survive stale and current translations', 'Stale translation completion preserves the active composer');
    await resolve(slowText, 'SA', 'تحتاج مراجعة الموصل إلى مستند إضافي.');
    await page.waitForFunction(() => document.querySelector('[data-message-id="REV-SLOW"] .chat-bubble')?.textContent === 'تحتاج مراجعة الموصل إلى مستند إضافي.');
    check(await page.inputValue('#conversationText') === 'Arabic view draft must survive stale and current translations', 'Current translation completion preserves the active composer');
    await language('ZH');
    check(await bubble('REV-SLOW').innerText() === '连接器评审还需要一份文档。', 'Previous-language translation is cached for the next language switch');
    check(await calls() === 4, 'Language changes reuse completed cache entries without duplicate calls');
    await addMessage('REV-SAME', '这是新收到的中文消息。', 'Chinese');
    check(await bubble('REV-SAME').innerText() === '这是新收到的中文消息。', 'Incoming content already in the current language appears directly');
    check(await calls() === 4, 'Same-language received content needs no translation call');
    const latestText = 'The revised sample set is ready.';
    await addMessage('REV-LATEST', latestText);
    await page.waitForFunction(() => window.__translationCalls.length === 5);
    await page.fill('#conversationText', 'A reply being composed after a new message');
    await resolve(latestText, 'ZH', '调整后的样本已经准备好了。');
    await page.waitForFunction(() => document.querySelector('[data-message-id="REV-LATEST"] .chat-bubble')?.textContent === '调整后的样本已经准备好了。');
    check(await page.inputValue('#conversationText') === 'A reply being composed after a new message', 'Later received messages translate automatically without clearing the reply draft');
    check(await page.locator('[data-message-id="REV-LATEST"] .chat-original').count() === 1, 'Received translations retain an optional original-text view');
    check(await page.locator('.chat-message.mine .chat-original').count() === 0, 'Own messages retain no original/translation switch');
    const senderTab = await context.newPage();
    senderTab.on('pageerror', error => errors.push(error.message));
    await senderTab.goto(base);
    await page.bringToFront();
    await page.fill('#conversationText', 'Draft preserved when another tab receives a message');
    await page.evaluate(() => { const input = document.querySelector('#conversationText'); input.focus(); input.setSelectionRange(6, 15); document.querySelector('.chat-messages').scrollTop = 0; });
    const crossTabText = 'A colleague uploaded the final approved document.';
    await senderTab.evaluate(text => {
      const latest = SaqrDB.load(), conversation = latest.conversations.find(item => item.id === 'CONV-001');
      conversation.messages.push({ id: 'REV-CROSS-TAB', senderId: 'USR-SELL-001', language: 'English', original: text, createdAt: new Date().toISOString() });
      SaqrDB.save(latest);
    }, crossTabText);
    await page.waitForFunction(() => window.__translationCalls.length === 6);
    check(await page.locator('[data-message-id="REV-CROSS-TAB"]').count() === 1, 'Real storage event displays a new message from another tab without manual navigation');
    check(await page.inputValue('#conversationText') === 'Draft preserved when another tab receives a message', 'Cross-tab received message preserves the composer draft');
    check(await page.evaluate(() => document.activeElement?.id === 'conversationText'), 'Cross-tab received message preserves composer focus');
    check(await page.evaluate(() => { const input = document.querySelector('#conversationText'); return input.selectionStart === 6 && input.selectionEnd === 15; }), 'Cross-tab received message preserves composer selection');
    check(await page.locator('.chat-messages').evaluate(node => node.scrollTop) === 0, 'Cross-tab received message preserves message scroll position');
    await resolve(crossTabText, 'ZH', '同事已上传最终批准的文档。');
    await page.waitForFunction(() => document.querySelector('[data-message-id="REV-CROSS-TAB"] .chat-bubble')?.textContent === '同事已上传最终批准的文档。');
    check(await page.inputValue('#conversationText') === 'Draft preserved when another tab receives a message', 'Cross-tab automatic translation preserves the pending reply draft');
    await senderTab.close();
    await page.evaluate(() => {
      SaqrAgents.runWorkspaceAgent = async ({ question }) => ({ markdown: `## Workspace response\n\nReceived: ${question}`, conversation_title: question.includes('renewal') ? 'Renewal follow-up' : 'Private Arabic product', provider: 'local', links: [], tool_trace: [] });
    });
    await go('buyer-agent');
    const initialSessions = await page.locator('button.agent-history-item').count();
    const firstSession = await page.getAttribute('.agent-workspace', 'data-agent-session');
    const firstQuestion = 'Find a private Arabic product for the procurement team';
    await page.fill('#workspaceAgentInput', firstQuestion);
    await page.click('#workspaceAgentForm button');
    await page.waitForFunction(() => document.querySelector('.agent-conversation')?.textContent.includes('Received: Find a private Arabic product'));
    check(await page.locator('.agent-bubble.assistant h2').count() === 1, 'Workspace conversation renders the response Markdown');
    await page.click('[data-action="new-agent-chat"]');
    check(await page.locator('button.agent-history-item').count() === initialSessions + 1, 'New conversation adds a history entry');
    check(await page.locator('.agent-bubble.user').count() === 0, 'New conversation starts with a fresh message area');
    const secondSession = await page.getAttribute('.agent-workspace', 'data-agent-session');
    check(firstSession !== secondSession, 'New conversation has its own session identity');
    const secondQuestion = 'Review renewal follow-up tasks';
    await page.fill('#workspaceAgentInput', secondQuestion);
    await page.click('#workspaceAgentForm button');
    await page.waitForFunction(() => document.querySelector('.agent-conversation')?.textContent.includes('Received: Review renewal follow-up tasks'));
    await page.locator(`button[data-agent-session="${firstSession}"]`).click();
    check(await page.locator('.agent-bubble.user').innerText() === firstQuestion, 'History selection restores its own question');
    check(!(await page.locator('.agent-conversation').innerText()).includes(secondQuestion), 'History selection keeps messages from other sessions separate');
    check(await page.locator(`button[data-agent-session="${firstSession}"]`).getAttribute('aria-current') === 'true', 'History selection marks the active session');
    await language('SA');
    check(await page.getAttribute('.agent-workspace', 'data-agent-session') === firstSession, 'Interface language switching retains the selected conversation');
    check(await page.locator('.agent-bubble.user').innerText() === firstQuestion, 'Interface language switching preserves original conversation messages');
    await page.reload();
    await page.waitForSelector('.agent-workspace');
    check(await page.getAttribute('.agent-workspace', 'data-agent-session') === firstSession, 'Reload restores the selected conversation from local history');
    check(await page.locator('.agent-bubble.user').innerText() === firstQuestion, 'Reload retains stored conversation content');
    await go('guide-agent');
    check(await page.locator('.agent-bubble.user').count() === 0, 'Guide conversation history stays separate from buyer history');
    await go('buyer-agent');
    await page.locator(`button[data-agent-session="${secondSession}"]`).click();
    check(await page.locator('.agent-bubble.user').innerText() === secondQuestion, 'Both conversations remain accessible after reload and role changes');
    check(unexpectedModelRequests.length === 0, 'Regression makes no actual model or API requests');
    check(errors.length === 0, 'Browser has no JavaScript errors: ' + errors.join('; '));
    console.log(`Marketplace revision browser regression: ${checks} checks passed.`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
